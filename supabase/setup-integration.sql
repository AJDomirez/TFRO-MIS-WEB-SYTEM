  for all to authenticated using (public.is_tfro_staff()) with check (public.is_tfro_staff());
drop policy if exists "Driver read own" on public.drivers;
create policy "Driver read own" on public.drivers
  for select to authenticated using (user_id = auth.uid());

-- FRANCHISE APPLICATIONS
