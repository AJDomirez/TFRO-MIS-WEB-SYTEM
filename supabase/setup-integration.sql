  for update to authenticated using (operator_id = auth.uid()) with check (operator_id = auth.uid());

-- FRANCHISE DOCUMENTS
alter table public.franchise_documents force row level security;
drop policy if exists "Staff all documents" on public.franchise_documents;
create policy "Staff all documents" on public.franchise_documents
  for all to authenticated using (public.is_tfro_staff()) with check (public.is_tfro_staff());
drop policy if exists "Operator own documents" on public.franchise_documents;
create policy "Operator own documents" on public.franchise_documents
  for select to authenticated using (
    exists (select 1 from public.franchise_applications a
            where a.id = application_id and a.operator_id = auth.uid())
  );
drop policy if exists "Operator insert documents" on public.franchise_documents;
create policy "Operator insert documents" on public.franchise_documents
  for insert to authenticated with check (
    exists (select 1 from public.franchise_applications a
            where a.id = application_id and a.operator_id = auth.uid())
  );
drop policy if exists "Operator update documents" on public.franchise_documents;
create policy "Operator update documents" on public.franchise_documents
  for update to authenticated using (
    exists (select 1 from public.franchise_applications a
            where a.id = application_id and a.operator_id = auth.uid())
  ) with check (
    exists (select 1 from public.franchise_applications a
            where a.id = application_id and a.operator_id = auth.uid())
  );

