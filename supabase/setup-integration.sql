create policy "Staff all applications" on public.franchise_applications
  for all to authenticated using (public.is_tfro_staff()) with check (public.is_tfro_staff());
drop policy if exists "Operator own applications" on public.franchise_applications;
create policy "Operator own applications" on public.franchise_applications
  for select to authenticated using (operator_id = auth.uid());
drop policy if exists "Operator insert application" on public.franchise_applications;
