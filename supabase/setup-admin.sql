-- ============================================================
-- AUDIT LOGS
-- ============================================================
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_name text,
  role text,
  action text not null,
  action_type text,
  ip_address text,
  created_at timestamptz not null default now()
);

alter table public.audit_logs enable row level security;

-- Make this script safe to re-run: drop existing policies first.
drop policy if exists "Staff can read audit logs" on public.audit_logs;
drop policy if exists "Users can insert audit logs" on public.audit_logs;

-- Staff/admin can read all audit logs.
create policy "Staff can read audit logs"
on public.audit_logs
for select
to authenticated
using ((select public.is_tfro_staff()));

-- Users can insert audit log entries (e.g., login, profile update).
create policy "Users can insert audit logs"
on public.audit_logs
for insert
to authenticated
with check (true);

-- Seed a few sample audit log entries.
insert into public.audit_logs (user_name, role, action, action_type, ip_address, created_at)
