  ('Jose Reyes', 'staff', 'Recorded violation for Ricardo Lim', 'violation', '192.168.1.12', now() - interval '5 hours'),
  ('Antonio Cruz', 'operator', 'Logged in to system', 'login', '192.168.1.25', now() - interval '1 day')
) as seed(user_name, role, action, action_type, ip_address, created_at)
where not exists (select 1 from public.audit_logs);

grant execute on function public.is_tfro_staff() to authenticated;

