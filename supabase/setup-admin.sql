-- Run this in Supabase Dashboard > SQL Editor.
-- Creates the notifications and audit_logs tables used by the admin pages,
-- with RLS policies so staff/admin can read them and users can manage
-- their own notifications.

-- ============================================================
-- NOTIFICATIONS
-- ============================================================
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null,
  message text not null,
  type text not null default 'info' check (type in ('urgent', 'info', 'warning', 'error')),
  user_id uuid references auth.users(id) on delete cascade,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.notifications enable row level security;

-- Reset every notification policy first. This also recovers cleanly from
-- earlier setup runs that created a policy before being interrupted.
do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'notifications'
  loop
    execute format('drop policy if exists %I on public.notifications', existing_policy.policyname);
  end loop;
end;
$$;

-- Staff/admin can read all notifications.
create policy "Staff can read all notifications"
on public.notifications
for select
to authenticated
using ((select public.is_tfro_staff()));

-- Users can read notifications addressed to them.
create policy "Users can read their own notifications"
on public.notifications
for select
to authenticated
using ((user_id is null) or (user_id = (select auth.uid())));

-- Users can mark their own notifications as read.
create policy "Users can update their own notifications"
on public.notifications
for update
to authenticated
using ((user_id = (select auth.uid())) or (user_id is null and (select public.is_tfro_staff())))
with check ((user_id = (select auth.uid())) or (user_id is null and (select public.is_tfro_staff())));

-- Users can delete their own notifications.
create policy "Users can delete their own notifications"
on public.notifications
for delete
to authenticated
using ((user_id = (select auth.uid())) or (user_id is null and (select public.is_tfro_staff())));

-- Staff/admin can create notifications.
create policy "Staff can create notifications"
on public.notifications
for insert
to authenticated
with check ((select public.is_tfro_staff()));

