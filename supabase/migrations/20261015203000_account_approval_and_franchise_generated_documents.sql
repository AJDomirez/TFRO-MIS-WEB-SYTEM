-- Portal authorization is separate from the requested role. Email confirmation
-- is still enforced by Supabase Auth; this status controls TFRO record approval.
alter table public.profiles
  add column if not exists account_status text not null default 'active';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'profiles_account_status_check'
      and conrelid = 'public.profiles'::regclass
  ) then
    alter table public.profiles add constraint profiles_account_status_check
      check (account_status in ('active', 'pending_verification', 'pending_approval', 'rejected', 'suspended'));
  end if;
end $$;

update public.profiles profile
set account_status = case
  when profile.role = 'operator' and exists (
    select 1 from public.operators operator_record
    where operator_record.user_id = profile.id and not operator_record.verified
  ) then 'pending_verification'
  else 'active'
end;

create table if not exists public.franchise_generated_documents (
  id bigint generated by default as identity primary key,
  franchise_id bigint not null references public.franchises(id) on delete cascade,
  renewal_id bigint references public.franchise_renewals(id) on delete cascade,
  source_type text not null default 'renewal'
    check (source_type in ('renewal', 'change_motor', 'payment')),
  source_id bigint not null,
  form_code text not null,
  document_name text not null,
  form_data jsonb not null default '{}'::jsonb,
  delivered_to_operator boolean not null default false,
  delivered_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint franchise_generated_documents_form_code_check
    check (form_code in ('TFRO-001', 'MTOP-PERMIT', 'TFRO-003', 'TFRO-004', 'TFRO-005', 'TFRO-007', 'TFRO-009', 'TFRO-010')),
  constraint franchise_generated_documents_source_unique unique (source_type, source_id, form_code)
);

create index if not exists franchise_generated_documents_franchise_id_idx
  on public.franchise_generated_documents (franchise_id, updated_at desc);
create index if not exists franchise_generated_documents_renewal_id_idx
  on public.franchise_generated_documents (renewal_id);

