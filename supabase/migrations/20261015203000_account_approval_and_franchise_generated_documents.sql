create or replace function public.approve_enforcer_account(p_enforcer_record_id bigint, p_approved boolean)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_user uuid;
begin
  if not exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role in ('admin', 'admin_viewer') and account_status = 'active'
  ) then
    raise exception 'Only TFRO administrators can approve Enforcer accounts';
  end if;

  select user_id into target_user
  from public.traffic_enforcers
  where id = p_enforcer_record_id
  for update;

  if target_user is null then
    raise exception 'This Enforcer ID has no linked signup account';
  end if;

  update public.profiles
  set account_status = case when p_approved then 'active' else 'rejected' end
  where id = target_user and role = 'traffic_enforcer';
  return found;
end;
$$;
revoke all on function public.approve_enforcer_account(bigint, boolean) from public, anon;
grant execute on function public.approve_enforcer_account(bigint, boolean) to authenticated;

create or replace function private.sync_approved_renewal_documents()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status = 'approved' then
    insert into public.franchise_generated_documents
      (franchise_id, renewal_id, source_type, source_id, form_code, document_name, delivered_to_operator, delivered_at, created_by, updated_by)
    values
      (new.franchise_id, new.id, 'renewal', new.id, 'MTOP-PERMIT', 'Motorized Tricycle Operator''s Permit', true, now(), new.reviewed_by, new.reviewed_by),
      (new.franchise_id, new.id, 'renewal', new.id, 'TFRO-003', 'PMBL Certification', true, now(), new.reviewed_by, new.reviewed_by),
      (new.franchise_id, new.id, 'renewal', new.id, 'TFRO-004', 'Checklist of Requirements', true, now(), new.reviewed_by, new.reviewed_by),
      (new.franchise_id, new.id, 'renewal', new.id, 'TFRO-005', 'Application for Motorized Tricycle Operator Permit', true, now(), new.reviewed_by, new.reviewed_by)
    on conflict (source_type, source_id, form_code) do update
      set delivered_to_operator = true,
          delivered_at = coalesce(public.franchise_generated_documents.delivered_at, excluded.delivered_at),
          updated_by = excluded.updated_by,
          updated_at = now();

    if new.temporary_mtop_issued then
      insert into public.franchise_generated_documents
        (franchise_id, renewal_id, source_type, source_id, form_code, document_name, delivered_to_operator, delivered_at, created_by, updated_by)
      values
        (new.franchise_id, new.id, 'renewal', new.id, 'TFRO-001', 'Temporary MTOP', true, now(), new.reviewed_by, new.reviewed_by)
      on conflict (source_type, source_id, form_code) do update
        set delivered_to_operator = true,
            delivered_at = coalesce(public.franchise_generated_documents.delivered_at, excluded.delivered_at),
            updated_by = excluded.updated_by,
            updated_at = now();
    end if;
  end if;
  return new;
end;
$$;
revoke all on function private.sync_approved_renewal_documents() from public, anon, authenticated;

