create or replace function private.notify_renewal_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  renewal_label text := coalesce(new.renewal_code, '#' || new.id);
begin
  if tg_op = 'INSERT' then
    insert into public.notifications (title, message, link, type, user_id)
    select 'New franchise renewal',
           'Franchise renewal ' || renewal_label || ' is pending TFRO review.',
           'renewals.html', 'info', profile.id
    from public.profiles profile where profile.role in ('admin', 'staff');
  elsif new.status is distinct from old.status then
    insert into public.notifications (title, message, link, type, user_id)
    values (
      'Franchise renewal update',
      case new.status
        when 'approved' then 'Your franchise renewal ' || renewal_label || ' is approved. Your MTOP is expected within 1-2 weeks.'
        when 'needs_correction' then 'Your franchise renewal ' || renewal_label || ' is not approved because requirements are incomplete: ' || coalesce(new.decision_reason, 'Please submit the missing requirements.')
        when 'rejected' then 'Your franchise renewal ' || renewal_label || ' was not approved: ' || coalesce(new.decision_reason, 'Please contact TFRO.')
        when 'awaiting_payment' then 'Your franchise renewal ' || renewal_label || ' is pending payment at the Treasurer''s Office.'
        when 'inspection_pending' then 'Documents for renewal ' || renewal_label || ' were verified. Vehicle inspection is pending.'
        else 'Your franchise renewal ' || renewal_label || ' status is now ' || replace(new.status, '_', ' ') || '.'
      end,
      'renewal.html',
      case when new.status = 'approved' then 'success'
           when new.status in ('needs_correction', 'rejected') then 'warning'
           else 'info' end,
      new.operator_id
    );

    if new.status = 'pending_review' and old.status = 'needs_correction' then
      insert into public.notifications (title, message, link, type, user_id)
      select 'Renewal requirements resubmitted',
             'Corrected requirements for renewal ' || renewal_label || ' are ready for review.',
             'renewals.html', 'info', profile.id
      from public.profiles profile where profile.role in ('admin', 'staff');
    end if;
  end if;
  return new;
end;
$$;

create trigger notify_renewal_event
after insert or update of status on public.franchise_renewals
for each row execute function private.notify_renewal_event();

create or replace function public.approve_franchise_renewal(
  p_renewal_id bigint,
  p_mtop_number text,
  p_expected_release_date date
)
returns date
language plpgsql
security invoker
set search_path = public, private, pg_temp
as $$
declare
  renewal public.franchise_renewals%rowtype;
  calculated_expiration date;
begin
  if not (select private.is_tfro_staff()) then
    raise exception 'Only TFRO Staff may approve franchise renewals';
  end if;

  select * into renewal
  from public.franchise_renewals
  where id = p_renewal_id
  for update;

  if not found then raise exception 'Renewal request was not found'; end if;
  if renewal.franchise_check_status = 'revoked' then
    raise exception 'A revoked franchise cannot be renewed';
  end if;
  if not renewal.documents_complete
    or (select count(*) from public.renewal_documents d where d.renewal_id = renewal.id and d.verified) <> 9
  then
    raise exception 'All nine renewal documents must be verified';
  end if;
  if not renewal.inspection_passed then raise exception 'Vehicle inspection must pass'; end if;
  if renewal.payment_status <> 'paid' then raise exception 'Treasurer payment must be confirmed'; end if;
  if nullif(trim(p_mtop_number), '') is null then raise exception 'MTOP number is required'; end if;

  calculated_expiration := (renewal.current_expiration_date + interval '3 years')::date;

  update public.franchises
  set status = 'active', application_type = 'renewal', application_date = current_date,
      expiration_date = calculated_expiration
  where id = renewal.franchise_id;

  update public.franchise_renewals
  set status = 'approved', decision_reason = null, mtop_number = trim(p_mtop_number),
      issuance_status = 'for_printing', expected_release_date = p_expected_release_date,
      new_expiration_date = calculated_expiration, reviewed_by = (select auth.uid()),
      reviewed_at = now(), updated_at = now()
  where id = renewal.id;

  return calculated_expiration;
end;
$$;

revoke all on function public.approve_franchise_renewal(bigint, text, date) from public, anon;
grant execute on function public.approve_franchise_renewal(bigint, text, date) to authenticated;
