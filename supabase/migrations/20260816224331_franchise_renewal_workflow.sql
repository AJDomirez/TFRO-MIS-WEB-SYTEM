-- Three-year franchise renewal workflow for Operators and TFRO Staff.

alter table public.franchises drop constraint if exists franchises_status_check;
alter table public.franchises
  add constraint franchises_status_check
  check (status in ('active', 'pending', 'expired', 'suspended', 'revoked'));

create table public.franchise_renewals (
  id bigint generated by default as identity primary key,
  operator_id uuid not null references public.profiles(id) on delete cascade,
  franchise_id bigint not null references public.franchises(id) on delete cascade,
  driver_id bigint references public.drivers(id) on delete set null,
  renewal_code text not null unique,
  renewal_type text not null check (renewal_type in ('regular', 'expired_or', 'change_motor')),
  current_expiration_date date not null,
  operator_name text not null,
  operator_address text not null,
  operator_contact text not null,
  voters_certificate_number text,
  cedula_number text,
  barangay_clearance_number text,
  driver_name text not null,
  driver_license_number text not null,
  plate_number text not null,
  engine_number text not null,
  chassis_number text not null,
  pmbl_certificate_number text,
  current_or_number text,
  current_cr_number text,
  or_registration_class text not null default 'for_hire'
    check (or_registration_class in ('for_hire', 'expired', 'private')),
  cr_registration_class text not null default 'for_hire'
    check (cr_registration_class in ('for_hire', 'private')),
  franchise_check_status text not null default 'pending'
    check (franchise_check_status in ('pending', 'up_to_date', 'expired', 'revoked')),
  status text not null default 'pending_review'
    check (status in (
      'pending_review', 'needs_correction', 'documents_verified',
      'inspection_pending', 'assessment_pending', 'awaiting_payment',
      'approved', 'rejected'
    )),
  decision_reason text,
  documents_complete boolean not null default false,
  inspection_results jsonb not null default '{}'::jsonb,
  inspection_passed boolean not null default false,
  inspection_remarks text,
  assessment_number text,
  assessment_date date,
  assessed_amount numeric(12,2) check (assessed_amount is null or assessed_amount >= 0),
  payment_status text not null default 'pending'
    check (payment_status in ('pending', 'paid')),
  payment_or_number text,
  temporary_mtop_issued boolean not null default false,
  temporary_mtop_issued_at timestamptz,
  mtop_number text,
  issuance_status text not null default 'not_ready'
    check (issuance_status in ('not_ready', 'for_printing', 'released')),
  expected_release_date date,
  new_expiration_date date,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index franchise_renewals_one_open_idx
on public.franchise_renewals (franchise_id)
where status not in ('approved', 'rejected');
create index franchise_renewals_operator_id_idx on public.franchise_renewals (operator_id);
create index franchise_renewals_driver_id_idx on public.franchise_renewals (driver_id);
create index franchise_renewals_status_idx on public.franchise_renewals (status, created_at desc);

create table public.renewal_documents (
  id bigint generated by default as identity primary key,
  renewal_id bigint not null references public.franchise_renewals(id) on delete cascade,
  doc_type text not null check (doc_type in (
    'voters_certificate', 'cedula', 'barangay_clearance', 'drivers_license',
    'picture_2x2', 'pmbl_certification', 'official_receipt',
    'certificate_registration', 'insurance'
  )),
  file_name text not null,
  storage_path text not null,
  file_size integer not null default 0 check (file_size >= 0),
  verified boolean not null default false,
  status text not null default 'pending'
    check (status in ('pending', 'verified', 'needs_correction')),
  staff_note text,
  uploaded_at timestamptz not null default now(),
  unique (renewal_id, doc_type)
);

create index renewal_documents_renewal_id_idx on public.renewal_documents (renewal_id);

alter table public.franchise_renewals enable row level security;
alter table public.franchise_renewals force row level security;
alter table public.renewal_documents enable row level security;
alter table public.renewal_documents force row level security;

revoke all on public.franchise_renewals, public.renewal_documents from anon, authenticated;
grant select, insert, update, delete on public.franchise_renewals to authenticated;
grant select, insert, update, delete on public.renewal_documents to authenticated;
grant usage, select on sequence public.franchise_renewals_id_seq to authenticated;
grant usage, select on sequence public.renewal_documents_id_seq to authenticated;

create policy "Authorized users read renewals"
on public.franchise_renewals for select to authenticated
using ((select private.is_tfro_staff()) or operator_id = (select auth.uid()));

create policy "Operators create renewals"
on public.franchise_renewals for insert to authenticated
with check (
  operator_id = (select auth.uid())
  and status = 'pending_review'
  and franchise_check_status = 'pending'
  and documents_complete = false
  and inspection_results = '{}'::jsonb
  and inspection_passed = false
  and assessed_amount is null
  and payment_status = 'pending'
  and temporary_mtop_issued = false
  and issuance_status = 'not_ready'
  and reviewed_by is null
  and reviewed_at is null
  and exists (
    select 1 from public.franchises franchise_record
    where franchise_record.id = franchise_id
      and franchise_record.operator_id = (select auth.uid())
      and franchise_record.status <> 'revoked'
  )
  and exists (
    select 1
    from public.drivers driver_record
    join public.operators operator_record on operator_record.id = driver_record.operator_id
    where driver_record.id = driver_id
      and operator_record.user_id = (select auth.uid())
  )
);

create policy "Authorized users update renewals"
on public.franchise_renewals for update to authenticated
using (
  (select private.is_tfro_staff())
  or (operator_id = (select auth.uid()) and status = 'needs_correction')
)
with check (
  (select private.is_tfro_staff())
  or (operator_id = (select auth.uid()) and status = 'pending_review')
);

create policy "Operators withdraw pending renewals"
on public.franchise_renewals for delete to authenticated
using (
  operator_id = (select auth.uid())
  and status = 'pending_review'
  and reviewed_by is null
);

