create or replace function private.guard_renewal_update()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  caller_role text;
begin
  select role into caller_role from public.profiles where id = (select auth.uid());
  if caller_role = 'operator' then
    if old.operator_id <> (select auth.uid())
      or old.status <> 'needs_correction'
      or new.status <> 'pending_review'
      or new.operator_id is distinct from old.operator_id
      or new.franchise_id is distinct from old.franchise_id
      or new.driver_id is distinct from old.driver_id
      or new.renewal_type is distinct from old.renewal_type
      or new.franchise_check_status is distinct from old.franchise_check_status
      or new.documents_complete is distinct from old.documents_complete
      or new.inspection_results is distinct from old.inspection_results
      or new.inspection_passed is distinct from old.inspection_passed
      or new.assessed_amount is distinct from old.assessed_amount
      or new.payment_status is distinct from old.payment_status
      or new.temporary_mtop_issued is distinct from old.temporary_mtop_issued
      or new.issuance_status is distinct from old.issuance_status
      or new.reviewed_by is distinct from old.reviewed_by
    then
      raise exception 'Operators may only resubmit a renewal after correcting documents';
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger guard_renewal_update
before update on public.franchise_renewals
for each row execute function private.guard_renewal_update();

create or replace function private.guard_renewal_document_update()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  caller_role text;
begin
  select role into caller_role from public.profiles where id = (select auth.uid());
  if caller_role = 'operator' then
    new.verified := false;
    new.status := 'pending';
    new.staff_note := null;
    new.uploaded_at := now();
  end if;
  return new;
end;
$$;

create trigger guard_renewal_document_update
before update on public.renewal_documents
for each row execute function private.guard_renewal_document_update();

